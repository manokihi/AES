import numpy as np
import matplotlib.pyplot as plt

"""## Step 1: Generate Checkerboard Data"""

def generate_data(n_samples=500, k=4):
    X = np.random.uniform(-1, 1, (n_samples, 2))

    # Checkerboard labels
    y = ((np.floor((X[:,0]+1)*k) + np.floor((X[:,1]+1)*k)) % 2)

    return X, y.reshape(-1, 1)

X, y = generate_data()

